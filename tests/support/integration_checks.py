"""Shared Uniform-fixture expectations; scientific tolerances remain test policy."""
import csv
import math
import re

from tpic_tools import vtk

LEVELS = ("double", "single-position", "single-position-velocity",
          "single-particles-moments-fields-double-mass", "single-particles-moments-fields")
# A precision is the pair "<storage>/<compute>" that outputs record. The strict
# tolerances of these scripts hold for double compute: every storage level with
# double compute, which needs a build with TPIC_BUILD_ALL_PRECISION_PAIRS=ON.
PRECISIONS = tuple(f"{storage}/double" for storage in LEVELS)
DT = 0.125
MOMENTS = ("rho", "J", "PXX", "PXY", "PXZ", "PYY", "PYZ", "PZZ")
STRICT_RTOL = 3e-10
STRICT_ATOL = 3e-12

def require(condition, message):
    if not condition:
        raise AssertionError(message)


def close(actual, expected, message):
    require(math.isfinite(actual) and math.isfinite(expected), message + ": nonfinite")
    require(math.isclose(actual, expected, rel_tol=STRICT_RTOL, abs_tol=STRICT_ATOL),
            f"{message}: {actual!r} != {expected!r}")


def precision_arguments(profile):
    storage, compute = profile.split("/")
    return ["--storage-precision", storage, "--compute-precision", compute]


def single_field_storage(profile):
    return profile.split("/")[0].startswith("single-particles-moments-fields")


def make_input(case, directory):
    # The default three species and ragged 7-cell partition exercise species totals
    # and a nonuniform two-rank halo.
    periodic = case["boundary"] == "periodic"
    def species_values(*values):
        return " ".join(str(values[index % len(values)]) for index in range(case["species"]))
    entries = {
        "Case": "Uniform", "dt": DT, "ncycles": case["cycles"], "th": 0.5,
        "GMREStol": "1e-10", "c": 1, "Lx": 7, "Ly": 3, "Lz": case["nz"],
        "nxc": 7, "nyc": 3, "nzc": case["nz"], "XLEN": case["ranks"],
        "YLEN": 1, "ZLEN": 1, "B0x": 0.25, "B0y": 0.125, "B0z": -0.0625,
        "ns": case["species"], "rhoINIT": species_values(1, 0.5, 0.5),
        "qom": species_values(-1, 1, 0.5), "npcelx": species_values(2), "npcely": species_values(2),
        "npcelz": species_values(2), "uth": species_values(0.1, 0.05, 0.025),
        "vth": species_values(0.1, 0.05, 0.025), "wth": species_values(0.1, 0.05, 0.025),
        "u0": species_values(0.125, -0.125, 0), "v0": species_values(0, 0, 0.0625),
        "w0": species_values(0), "CenterInitialVelocity": species_values("true"), "FieldOutputCycle": 1,
        "DiagnosticsOutputCycle": 1, "ParticlesOutputCycle": 0, "RestartOutputCycle": 0,
        "FieldOutputTag": "E+B",
        "MomentsOutputTag": "+".join(name for base in MOMENTS for name in (base, base + "_tot")),
        "ECSimSmoothing": "energy_conserving" if case["smoothing"] else "none",
        "Smooth": 0.5, "SmoothNiter": 2, "SaveDirName": directory / "output",
    }
    for axis in "XYZ":
        entries["PERIODIC" + axis] = str(periodic).lower()
        entries["PERIODIC" + axis + "_P"] = str(periodic).lower()
        for face in ("left", "right"):
            entries["bcEMface" + axis + face] = int(case["boundary"] == "pmc")
            entries["bcPface" + axis + face] = 1
    return "# Generated by tests/support/integration_checks.py\n" + "".join(
        f"{key} = {value}\n" for key, value in entries.items())


def metadata(image, cycle, final_state, precision=None):
    actual_cycle, time, final, profile = vtk.metadata(image)
    require(actual_cycle == cycle, "incorrect VTK cycle")
    close(time, cycle * DT, "incorrect VTK time")
    require(final == final_state, "incorrect VTK final flag")
    if precision is not None:
        require(profile == precision, f"incorrect VTK precision profile: {profile!r} != {precision!r}")
        roles = next(a.text for a in image.find("FieldData") if a.get("Name") == "precision_roles")
        roles = bytes(map(int, roles.split())).rstrip(b"\0").decode()
        require("float64" in roles, "missing FP64 role metadata")
        require(("float32" in roles) == (precision != "double/double"), "incorrect mixed role metadata")


def check_csv(case, directory):
    content = (directory / "diagnostics.csv").read_text()
    if "precision" in case:
        profile = re.search(r"^# precision_profile = (.+)$", content, re.MULTILINE)
        require(profile is not None and profile[1] == case["precision"],
                "incorrect CSV precision profile")
    rows = list(csv.DictReader(line for line in content.splitlines() if not line.startswith("#")))
    require(len(rows) == case["cycles"] + 1, "incorrect diagnostic row count")
    initial_energy = None
    for cycle, row in enumerate(rows):
        require(int(row["cycle"]) == cycle, "CSV cycles are not increasing from zero")
        close(float(row["time"]), cycle * DT, "CSV time")
        require(row["state"] == ("final" if cycle == case["cycles"] else "pre_solve"),
                "CSV state label")
        values = {name: float(value) for name, value in row.items() if name != "state"}
        require(all(math.isfinite(value) for value in values.values()), "nonfinite CSV value")
        for name in ("kinetic_energy", "charge", "momentum_x", "momentum_y", "momentum_z"):
            close(values[name], sum(values[f"{name}_{species}"] for species in range(case["species"])),
                  "CSV species total " + name)
        close(values["total_energy"], sum(values[name] for name in
              ("electric_energy", "magnetic_energy", "kinetic_energy")), "CSV total energy")
        if initial_energy is None:
            initial_energy = values["total_energy"]
        close(values["total_energy_change"], values["total_energy"] - initial_energy,
              "CSV energy change")
    return dict(rows=len(rows), initial_energy=initial_energy,
                final_energy=float(rows[-1]["total_energy"]))


def check_counts(case, log):
    per_species = 7 * 3 * case["nz"] * 8
    require(re.search(r"Timesteps completed\s*:\s*" + str(case["cycles"]) + r"\b", log),
            "missing/incorrect completed timestep report")
    require(re.search(r"Species / final particles\s*:\s*" + str(case["species"]) + r"\s*/\s*" +
                      str(case["species"] * per_species) + r"\b", log),
            "missing/incorrect final particle report")
    for species in range(case["species"]):
        require(re.search(r"Species " + str(species) + r"\s*:\s*" +
                          str(per_species) + r" particles\b", log),
                "missing/incorrect reported species population")
    require(len(re.findall(r"Maxwell GMRES\s*: converged", log)) == case["cycles"],
            "missing GMRES convergence report")
    return dict(global_particles=case["species"] * per_species,
                species_particles=[per_species] * case["species"])

